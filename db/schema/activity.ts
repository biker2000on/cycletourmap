import { pgTable, uuid, text, integer, bigint, doublePrecision, boolean, timestamp, index } from 'drizzle-orm/pg-core'
import { users } from './users'

export const activities = pgTable('Activity', {
  id: uuid('id').primaryKey().defaultRandom(),
  activityType: text('activity_type').notNull(),
  stravaId: bigint('strava_id', { mode: 'number' }),
  achievementCount: integer('achievement_count'),
  athleteCount: integer('athlete_count'),
  averageHeartrate: integer('average_heartrate'),
  averageSpeed: doublePrecision('average_speed'),
  averageTemp: doublePrecision('average_temp'),
  averageWatts: integer('average_watts'),
  commentCount: integer('comment_count'),
  commute: boolean('commute'),
  description: text('description'),
  deviceWatts: doublePrecision('device_watts'),
  displayHideHeartrateOption: boolean('display_hide_heartrate_option'),
  distance: doublePrecision('distance'),
  elapsedTime: doublePrecision('elapsed_time'),
  elevHigh: doublePrecision('elev_high'),
  elevLow: doublePrecision('elev_low'),
  endLatlng: text('end_latlng'),
  flagged: boolean('flagged'),
  gearId: integer('gear_id'),
  hasHeartrate: boolean('has_heartrate'),
  hasKudoed: boolean('has_kudoed'),
  heartrateOptOut: boolean('heartrate_opt_out'),
  kilojoules: integer('kilojoules'),
  kudosCount: integer('kudos_count'),
  locationCity: text('location_city'),
  locationCountry: text('location_country'),
  locationState: text('location_state'),
  manual: boolean('manual'),
  summaryPolyline: text('summary_polyline'),
  maxHeartrate: integer('max_heartrate'),
  maxSpeed: doublePrecision('max_speed'),
  movingTime: doublePrecision('moving_time'),
  name: text('name'),
  photoCount: integer('photo_count'),
  prCount: integer('pr_count'),
  private: boolean('private'),
  resourceState: text('resource_state'),
  startDate: timestamp('start_date', { precision: 3 }),
  startDateLocal: timestamp('start_date_local', { precision: 3 }),
  startLatitude: doublePrecision('start_latitude'),
  startLongitude: doublePrecision('start_longitude'),
  startLatlng: text('start_latlng'),
  timezone: text('timezone'),
  totalElevationGain: doublePrecision('total_elevation_gain'),
  totalPhotoCount: integer('total_photo_count'),
  trainer: boolean('trainer'),
  type: text('type'),
  uploadId: integer('upload_id'),
  utcOffset: text('utc_offset'),
  visibility: boolean('visibility'),
  workoutType: text('workout_type'),
  userId: uuid('user_id').notNull().references(() => users.id, { onDelete: 'restrict', onUpdate: 'cascade' }),
  createdAt: timestamp('created_at').defaultNow(),
  modifiedAt: timestamp('modified_at').defaultNow(),
}, (table) => [
  index('Activity_user_id_fk').on(table.userId),
])
